import { describe, expect, it } from "vitest";
import {
	NO_TITLE_TRACK,
	type TitleChange,
	type TitleTrack,
	titleChange,
	titleGraceEnded,
} from "../agentTitleMap";
import fixture from "./fixtures/titleStatus.json";

/**
 * Sequences of terminal titles (and grace windows running out) through the
 * Window's `titleChange`, step by step. The cases are in
 * `fixtures/titleStatus.json`, which Rust's `title_status.rs` replays and must
 * match (docs/plans/remote-hosts.md phase 6d-3).
 *
 * Regenerate after a change:
 * `UPDATE_TITLE_STATUS=1 npx vitest run src/lib/__tests__/titleStatus.test.ts`
 */

const NODE_FS = "node:fs";

type Step =
	| { title: string; expected: TitleChange }
	| { graceEnded: true; expected: { track: TitleTrack } };

interface Case {
	agent: string | null;
	steps: Step[];
}

const TITLES = [
	"",
	"Vibe",
	">> Vibe",
	"? Vibe",
	">> fix the tests",
	"? fix the tests",
	"Vibe - Action Required",
	"Vibe - Task Complete",
	"fix the tests - Action Required",
	">>Vibe",
	"?",
];

/** A small deterministic generator, so the fixture never churns. */
function rng(seed: number): () => number {
	let x = seed;
	return () => {
		x = (x * 1103515245 + 12345) & 0x7fffffff;
		return x / 0x7fffffff;
	};
}

function generate(): Case[] {
	const cases: Case[] = [];
	const next = rng(42);
	for (const agent of ["vibe", "claude", null]) {
		const count = agent === "vibe" ? 300 : 10;
		for (let n = 0; n < count; n++) {
			let track = NO_TITLE_TRACK;
			const steps: Step[] = [];
			const length = 2 + Math.floor(next() * 10);
			for (let i = 0; i < length; i++) {
				if (next() < 0.15) {
					track = titleGraceEnded(track);
					steps.push({ graceEnded: true, expected: { track } });
					continue;
				}
				const title = TITLES[Math.floor(next() * TITLES.length)];
				const change = titleChange(track, agent ?? undefined, title);
				track = change.track;
				steps.push({ title, expected: change });
			}
			cases.push(JSON.parse(JSON.stringify({ agent, steps })));
		}
	}
	return cases;
}

describe("title status", () => {
	const cases = generate();

	it("covers every kind of outcome", () => {
		const outcomes = new Set(
			cases.flatMap((c) =>
				c.steps.map((s) =>
					"title" in s
						? `${s.expected.dispatch?.status ?? "-"}/${s.expected.dispatch?.startsTurn ?? "-"}/${s.expected.awaitTurnEnd}`
						: "grace",
				),
			),
		);
		for (const o of [
			"working/true/false",
			"working/false/false",
			"waiting/false/false",
			"none/false/true",
			"-/-/false",
			"grace",
		]) {
			expect(outcomes).toContain(o);
		}
	});

	it("resumes a Turn across a bare title inside the grace window", () => {
		let t = titleChange(NO_TITLE_TRACK, "vibe", "? Vibe").track;
		t = titleChange(t, "vibe", "Vibe").track;
		const r = titleChange(t, "vibe", ">> Vibe");
		expect(r.dispatch).toEqual({ status: "working", startsTurn: false });
	});

	it("matches the fixture Rust replays", async () => {
		const proc = (
			globalThis as {
				process?: { env?: Record<string, string>; cwd(): string };
			}
		).process;
		if (proc?.env?.UPDATE_TITLE_STATUS) {
			const fs = (await import(/* @vite-ignore */ NODE_FS)) as {
				writeFileSync(path: string, data: string): void;
			};
			fs.writeFileSync(
				`${proc.cwd()}/src/lib/__tests__/fixtures/titleStatus.json`,
				`${JSON.stringify({ _comment: "Generated by titleStatus.test.ts; replayed by title_status.rs.", cases })}\n`,
			);
			return;
		}
		expect(cases).toEqual((fixture as unknown as { cases: Case[] }).cases);
	});
});
